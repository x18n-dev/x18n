/** ---- Run ---- */

async function main(): Promise<void> {
  const check = process.argv.includes('--check')
  await configPage()
  await cliPage()
  await contractsPage()
  await lspPage()
  await mcpPage()
  await glossaryPage()
  outputs.set('content/6.references/.navigation.yml', 'title: Reference\n')
  await errorPages()
  checkPages()
  await markedPages()

  const stale: string[] = []
  for (const dir of generatedDirs) {
    for (const file of existsSync(join(docs, dir)) ? await readdir(join(docs, dir)) : []) {
      const path = `${dir}/${file}`
      if (file.endsWith('.md') && !outputs.has(path))
        stale.push(path)
    }
  }
  const changed: string[] = []
  for (const [path, content] of outputs) {
    const file = join(docs, path)
    if ((existsSync(file) ? await readFile(file, 'utf8') : undefined) !== content)
      changed.push(path)
  }

  if (check) {
    if (changed.length || stale.length) {
      process.stderr.write(`Generated docs are out of date. Run \`pnpm -C docs run generate\`.\n${[...changed, ...stale].map(p => `  ${p}`).join('\n')}\n`)
      process.exitCode = 1
    }
    return
  }
  for (const path of changed) {
    await mkdir(dirname(join(docs, path)), { recursive: true })
    await writeFile(join(docs, path), outputs.get(path)!)
  }
  for (const path of stale)
    await rm(join(docs, path))
  // Served at https://x18n.antfu.dev/schema/*.json; rebuilt on every run, so not committed.
  await mkdir(join(docs, 'public/schema'), { recursive: true })
  await writeFile(join(docs, 'public/schema/config.json'), `${JSON.stringify(buildJsonSchema(ConfigSchema, 'x18n config'), null, 2)}\n`)
  await writeFile(join(docs, 'public/schema/plugin.json'), `${JSON.stringify(buildJsonSchema(PluginFileSchema, 'x18n YAML plugin'), null, 2)}\n`)
  process.stdout.write(`Generated ${outputs.size} files (${changed.length} changed, ${stale.length} removed).\n`)
}

await main()
