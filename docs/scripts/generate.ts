/** Defaults that are not part of the resolved config. */
const configDefaults: { readonly [path: string]: string } = {
  root: 'the directory of the config file',
  presets: '`\'auto\'`',
  plugins: '`[]`',
  history: '`true`',
}

function valueAt(value: unknown, path: readonly string[]): unknown {
  return path.reduce<unknown>((current, key) => typeof current === 'object' && current !== null ? new Map(Object.entries(current)).get(key) : undefined, value)
}

function formatDefault(value: unknown): string | undefined {
  if (value === undefined)
    return undefined
  const json = JSON.stringify(value)
  if (Array.isArray(value) && json.length > 60)
    return `\n\n${value.map(item => `  - ${code(String(item))}`).join('\n')}`
  return code(json)
}

async function configPage(): Promise<void> {
  const text = await source('packages/core/src/types/config.ts')
  const used = new Set<string>()
  const documented = (iface: string): Field[] => fields(text, iface).map((field) => {
    const id = `${iface}.${field.name}`
    const doc = field.doc ?? configNotes[id]
    if (!doc)
      throw new Error(`config field ${id} has no JSDoc and no entry in notes.ts`)
    if (!field.doc)
      used.add(id)
    return { ...field, doc }
  })
  const schema = buildJsonSchema(ConfigSchema, 'x18n config') as JsonSchema // `buildJsonSchema` returns a plain JSON Schema object
  const { config: resolved } = await resolveConfig({ host: createMemoryHost(), config: {}, builtins: { plugins: [], presets: {} } })
  const sections: string[] = []

  function verify(node: ConfigNode, object: JsonSchema | undefined, path: string): Field[] {
    const list = documented(node.iface)
    const expected = Object.keys(object?.properties ?? {}).sort().join(', ')
    const actual = list.map(f => f.name).sort().join(', ')
    if (expected !== actual)
      throw new Error(`config ${path || '(root)'}: schema has [${expected}], ${node.iface} has [${actual}]`)
    return list
  }

  function itemTable(node: ConfigNode, object: JsonSchema | undefined, path: string): string {
    const list = verify(node, object, path)
    return table(['Field', 'Type', 'Description'], list.map(f => [
      `${code(f.name)}${object?.required?.includes(f.name) ? '' : '?'}`,
      code(f.type),
      f.doc!,
    ]))
  }

  function walk(node: ConfigNode, object: JsonSchema | undefined, path: readonly string[], depth: number): void {
    for (const field of verify(node, object, path.join('.'))) {
      const fieldPath = [...path, field.name]
      const id = fieldPath.join('.')
      const child = node.children?.[field.name]
      const property = object?.properties?.[field.name]
      const isObject = child !== undefined && property?.type === 'object'
      const resolvedDefault = isObject ? undefined : configDefaults[id] ?? formatDefault(valueAt(resolved, fieldPath))
      const lines = [`${'#'.repeat(depth)} ${code(id)}`, '', `Type: ${code(isObject ? 'object' : field.type)}`]
      if (resolvedDefault)
        lines.push('', `Default:${resolvedDefault.startsWith('\n') ? '' : ' '}${resolvedDefault}`)
      lines.push('', field.doc!)
      sections.push(lines.join('\n'))
      if (!child)
        continue
      const childObject = objectOf(property)
      if (isObject) {
        walk(child, childObject, fieldPath, depth + 1)
        continue
      }
      sections.push(`Each item of ${code(id)}:\n\n${itemTable(child, childObject, id)}`)
      for (const [name, grandchild] of Object.entries(child.children ?? {}))
        sections.push(`${grandchild.caption ?? code(`${id}[].${name}`)}:\n\n${itemTable(grandchild, objectOf(childObject?.properties?.[name]), `${id}.${name}`)}`)
    }
  }
  walk(configTree, schema, [], 3)

  const tsOnly = documented('UserConfig')
  const unused = Object.keys(configNotes).filter(id => !used.has(id))
  if (unused.length)
    throw new Error(`notes.ts has config notes for fields that have JSDoc or do not exist: ${unused.join(', ')}`)
  page('content/6.references/1.config.md', 'Config reference', 'Every option of x18n.config.ts, x18n.config.yml and x18n.config.json.', `
This page lists every option of the config file. Read [Configuration](/guide/configuration) first for the file names and how x18n finds them.

YAML and JSON configs are validated with a JSON Schema. Point your editor at it:

- YAML: \`# yaml-language-server: $schema=https://x18n.antfu.dev/schema/config.json\` as the first line.
- JSON: \`"$schema": "https://x18n.antfu.dev/schema/config.json"\`.

\`x18n schema config\` prints the same schema. A default is the value before presets run. Presets add resources, call specs, derived keys and extraction templates on top of it.

## Options

${sections.join('\n\n')}

## TypeScript only

\`defineConfig\` in \`x18n.config.ts\` accepts more than YAML and JSON. These options take plugin objects and functions:

${table(['Option', 'Type', 'Description'], tsOnly.map(f => [code(f.name), code(f.type), f.doc!]))}

A \`PluginSpecifier\` is a string (a built-in preset name, a package name or a path), or \`[specifier, options]\`. A \`CheckSetting\` is a severity (\`'error'\`, \`'warning'\`, \`'info'\`, \`'hint'\` or \`'off'\`), or \`[severity, options]\`.
`)
}

