/** ---- Errors ---- */

async function sourceFiles(): Promise<Map<string, string>> {
  const files = new Map<string, string>()
  for (const pkg of await readdir(join(repo, 'packages'))) {
    const dir = join(repo, 'packages', pkg, 'src')
    if (!existsSync(dir))
      continue
    for (const file of await readdir(dir, { recursive: true })) {
      if (file.endsWith('.ts') && !file.includes('generated'))
        files.set(`packages/${pkg}/src/${file.replace(/\\/g, '/')}`, await readFile(join(dir, file), 'utf8'))
    }
  }
  return files
}

