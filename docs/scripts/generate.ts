/** ---- Generated blocks inside hand-written pages ---- */

/** Replaces the text between `<!-- generated:<name> -->` and `<!-- /generated:<name> -->` in a page. */
async function fillMarkers(path: string, blocks: { readonly [name: string]: string }): Promise<void> {
  let text = await readFile(join(docs, path), 'utf8')
  for (const [name, block] of Object.entries(blocks)) {
    const marker = new RegExp(`(<!-- generated:${name} -->)[\\s\\S]*?(<!-- /generated:${name} -->)`)
    if (!marker.test(text))
      throw new Error(`${path} has no generated:${name} markers`)
    text = text.replace(marker, `$1\n\n${block}\n\n$2`)
  }
  outputs.set(path, text)
}

