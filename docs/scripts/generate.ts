/** ---- TypeScript declarations, read as text ---- */

/** The text of `interface <name>` or `type <name>` with its JSDoc, from a source file. */
function declaration(text: string, name: string): string {
  const start = new RegExp(`^(?:/\\*\\*.*\\*/\\n)?(?:export )?(?:interface|type) ${name}\\b`, 'm').exec(text)
  if (!start)
    throw new Error(`declaration ${name} not found`)
  const rest = text.slice(start.index)
  const end = /^\}$/m.exec(rest)
  const blank = rest.indexOf('\n\n')
  const isInterface = /^(?:\/\*\*.*\*\/\n)?(?:export )?interface/.test(rest)
  return isInterface && end ? rest.slice(0, end.index + 1) : rest.slice(0, blank === -1 ? undefined : blank)
}

interface Field {
  readonly name: string
  readonly type: string
  readonly doc: string | undefined
}

/** Members of an interface whose members each sit on one line, as in `types/config.ts`. */
function fields(text: string, name: string): Field[] {
  const out: Field[] = []
  let doc: string | undefined
  for (const line of declaration(text, name).split('\n').slice(1, -1)) {
    const comment = /^\s*\/\*\*(.*)\*\/$/.exec(line)
    if (comment) {
      doc = comment[1]!.trim()
      continue
    }
    const member = /^ {2}readonly ([$\w]+)\??: (.+)$/.exec(line)
    if (member) {
      out.push({ name: member[1]!, type: member[2]!.replace(/readonly /g, '').replace(/ \| undefined$/, ''), doc })
      doc = undefined
    }
  }
  return out
}

/** ---- JSON Schema ---- */

interface JsonSchema {
  readonly type?: string
  readonly enum?: readonly string[]
  readonly const?: string | number | boolean
  readonly properties?: { readonly [name: string]: JsonSchema }
  readonly required?: readonly string[]
  readonly items?: JsonSchema
  readonly anyOf?: readonly JsonSchema[]
  readonly description?: string
}

/** The object schema at a property, looking through arrays and unions. */
function objectOf(schema: JsonSchema | undefined): JsonSchema | undefined {
  if (!schema)
    return undefined
  if (schema.properties)
    return schema
  return objectOf(schema.items) ?? schema.anyOf?.map(objectOf).find(Boolean)
}

function schemaType(schema: JsonSchema): string {
  if (schema.anyOf)
    return schema.anyOf.map(schemaType).join(' | ')
  if (schema.enum)
    return schema.enum.map(value => `'${value}'`).join(' | ')
  if (schema.const !== undefined)
    return JSON.stringify(schema.const)
  if (schema.type === 'array')
    return `${schema.items ? schemaType(schema.items) : 'unknown'}[]`
  return schema.type ?? 'unknown'
}

